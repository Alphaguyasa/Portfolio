// Generates src/components/brand-logos.tsx from the simple-icons package so the tool
// tiles render vendored inline SVG instead of hot-linking cdn.simpleicons.org.
// Re-run after bumping simple-icons: `node scripts/generate-brand-logos.mjs`
import { writeFile } from "node:fs/promises";
import path from "node:path";
import * as si from "simple-icons";

// Colours are the design's, not always the brand default (Next.js is inked to #0A0A0A).
const wanted = [
  { key: "nextjs", icon: si.siNextdotjs, color: "#0A0A0A" },
  { key: "react", icon: si.siReact, color: "#61DAFB" },
  { key: "typescript", icon: si.siTypescript, color: "#3178C6" },
  { key: "flutter", icon: si.siFlutter, color: "#02569B" },
  { key: "kotlin", icon: si.siKotlin, color: "#7F52FF" },
  { key: "postgresql", icon: si.siPostgresql, color: "#4169E1" },
];

const entries = wanted
  .map(
    ({ key, icon, color }) =>
      `  ${key}: {\n    title: ${JSON.stringify(icon.title)},\n    color: ${JSON.stringify(color)},\n    path: ${JSON.stringify(icon.path)},\n  },`,
  )
  .join("\n");

const out = `// GENERATED by scripts/generate-brand-logos.mjs — do not edit by hand.
// Vendored from the simple-icons package (CC0) so nothing is fetched from a CDN at runtime.

export type BrandLogoKey =
${wanted.map(({ key }) => `  | ${JSON.stringify(key)}`).join("\n")};

export const brandLogos: Record<
  BrandLogoKey,
  { title: string; color: string; path: string }
> = {
${entries}
};

export function BrandLogo({
  name,
  size = 44,
  className,
}: {
  name: BrandLogoKey;
  size?: number;
  className?: string;
}) {
  const logo = brandLogos[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={logo.color}
      role="img"
      aria-label={logo.title}
      className={className}
    >
      <path d={logo.path} />
    </svg>
  );
}
`;

const dest = path.join(process.cwd(), "src", "components", "brand-logos.tsx");
await writeFile(dest, out, "utf8");
console.log(`wrote ${dest} (${wanted.length} logos)`);
